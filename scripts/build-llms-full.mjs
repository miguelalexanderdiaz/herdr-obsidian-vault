#!/usr/bin/env node
// Builds docs/llms-full.txt: README.md, AGENTS.md and the text of every page of the docs site as one plain
// text file for AI agents (the long companion of llms.txt). No dependencies; Node 22+.
//
//   node scripts/build-llms-full.mjs            write docs/llms-full.txt
//   node scripts/build-llms-full.mjs --check    exit 1 when the committed file is not what a fresh build gives
//   node scripts/build-llms-full.mjs --root DIR build or check another copy
//
// check-docs.mjs imports buildLlmsFull() and fails when the committed file is stale, so the two cannot drift.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ENTITIES = {
  lt: "<", gt: ">", quot: '"', amp: "&", nbsp: " ", rsquo: "’", lsquo: "‘", ldquo: "“", rdquo: "”",
  hellip: "…", mdash: "—", ndash: "–", larr: "←", rarr: "→",
};
const decode = (s) => s.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (all, e) => {
  if (e[0] === "#") {
    const n = e[1].toLowerCase() === "x" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10);
    return Number.isFinite(n) ? String.fromCodePoint(n) : all;
  }
  return ENTITIES[e.toLowerCase()] ?? all;
});

const PAGES = ["index", "install", "usage", "requirements", "configuration", "privacy", "troubleshooting", "for-agents"];

function htmlToText(html) {
  const main = (html.match(/<main[\s>][\s\S]*<\/main>/i) || [html])[0];
  let s = main.replace(/<!--[\s\S]*?-->/g, "");
  s = s.replace(/<figure>[\s\S]*?<\/figure>/gi, (fig) => {
    const alt = (fig.match(/<title[^>]*>([\s\S]*?)<\/title>/i) || fig.match(/\salt="([^"]*)"/i) || [])[1];
    return alt ? `\n[figure: ${alt}]\n` : "\n";
  });
  s = s.replace(/<svg[\s\S]*?<\/svg>/gi, "");
  const pres = [];
  s = s.replace(/<pre[^>]*>([\s\S]*?)<\/pre>/gi, (_, body) => {
    pres.push(decode(body.replace(/<[^>]+>/g, "")).replace(/\s+$/, ""));
    return `\n\u0000PRE${pres.length - 1}\u0000\n`;
  });
  s = s.replace(/<h([1-6])[^>]*>([\s\S]*?)<\/h\1>/gi, (_, n, t) => `\n\n${"#".repeat(Number(n))} ${t.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim()}\n\n`);
  s = s.replace(/<tr[^>]*>([\s\S]*?)<\/tr>/gi, (_, row) => {
    const cells = [...row.matchAll(/<t[hd][^>]*>([\s\S]*?)<\/t[hd]>/gi)].map((c) => c[1].replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim());
    return `\n${cells.join(" | ")}\n`;
  });
  s = s.replace(/<li[^>]*>/gi, "\n- ").replace(/<\/(p|ul|ol|div|table|figure|details|summary|dl|dd|dt)>/gi, "\n").replace(/<br\s*\/?>/gi, "\n");
  s = s.replace(/<[^>]+>/g, "");
  s = decode(s).replace(/[ \t]+\n/g, "\n").replace(/[ \t]{2,}/g, " ").replace(/\n{3,}/g, "\n\n").trim();
  s = s.replace(/\u0000PRE(\d+)\u0000/g, (_, i) => "```\n" + pres[Number(i)] + "\n```");
  return s;
}

function mdToText(md) {
  return md.replace(/<!--[\s\S]*?-->/g, "").replace(/\n{3,}/g, "\n\n").trim();
}

export function buildLlmsFull(root) {
  const read = (p) => fs.readFileSync(path.join(root, p), "utf8");
  const parts = [
    "# Herdr Obsidian Vault: full text for agents\n\n" +
    "This file is generated by scripts/build-llms-full.mjs from README.md, AGENTS.md and the pages of the docs site. " +
    "Do not edit it; edit the sources and rebuild. The short index is llms.txt.",
  ];
  const add = (label, body) => parts.push(`\n\n---\n\n<source: ${label}>\n\n${body}`);
  add("README.md", mdToText(read("README.md")));
  add("AGENTS.md", mdToText(read("AGENTS.md")));
  for (const p of PAGES) {
    const file = `docs/${p}.html`;
    if (fs.existsSync(path.join(root, file))) add(file, htmlToText(read(file)));
  }
  return parts.join("") + "\n";
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const i = process.argv.indexOf("--root");
  const root = path.resolve(i > 0 ? process.argv[i + 1] : path.join(path.dirname(fileURLToPath(import.meta.url)), ".."));
  const out = path.join(root, "docs", "llms-full.txt");
  const fresh = buildLlmsFull(root);
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
    if (have !== fresh) {
      console.error("build-llms-full: docs/llms-full.txt is " + (have === null ? "missing" : "stale") + " (run: node scripts/build-llms-full.mjs)");
      process.exit(1);
    }
    console.log("build-llms-full: docs/llms-full.txt is current");
  } else {
    fs.writeFileSync(out, fresh);
    console.log(`build-llms-full: wrote docs/llms-full.txt (${fresh.length} characters)`);
  }
}
